export function faqPageSchema(items: FaqItem[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    inLanguage: "ru-RU",
    speakable: {
      "@type": "SpeakableSpecification",
      cssSelector: ["h1", "h2", "h3", "[data-faq-answer]"],
    },
    mainEntity: items.map((item) => ({
      "@type": "Question",
      name: item.question,
      acceptedAnswer: {
        "@type": "Answer",
        text: item.answer,
      },
    })),
  };
}
